#!/bin/sh
# Build the engine, install a terminal wrapper in <repo>/bin, register that
# directory on PATH in shell rc files, and (when possible) install an
# executable launcher in a system bin directory. Safe to re-run.
set -eu

escape_single_quote() {
    printf '%s' "$1" | sed "s/'/'\\\\''/g"
}

die() {
    echo "install-cli.sh: $*" >&2
    exit 1
}

force=0
case "${1:-}" in
    --force) force=1 ;;
    '') ;;
    *) die "usage: sh scripts/install-cli.sh [--force]" ;;
esac

[ -n "${HOME:-}" ] || die "HOME is not set"

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
root=$(CDPATH= cd -- "$script_dir/.." && pwd -P)
[ -f "$root/mini-mvn" ] || die "cannot find $root/mini-mvn"
[ -f "$root/scripts/find-jdk17.sh" ] || die "cannot find scripts/find-jdk17.sh"

jar=${MINI_MVN_JAR:-$root/target/mini-maven/mini-mvn.jar}
bin=$root/bin
wrapper=$bin/mini-mvn
user_rc=${MINI_MVN_RC:-$HOME/.bashrc}
link_dir=${MINI_MVN_LINK_DIR:-/usr/local/bin}
link=$link_dir/mini-mvn
marker_begin='# >>> mini-mvn cli >>>'
marker_end='# <<< mini-mvn cli <<<'

# A launcher in a normal bin directory is preferred over a shell function:
# /shared may be mounted noexec, so the project wrapper itself cannot be run
# directly, but a stub on an exec-capable filesystem can.
use_link=0
case "${MINI_MVN_NO_LINK:-0}" in
    1|true|yes) ;;
    *)
        if [ -d "$link_dir" ] && [ -w "$link_dir" ]; then
            use_link=1
        fi
        ;;
esac

# Interactive bash reads ~/.bashrc; login shells (sh/ash/bash -l) read
# ~/.profile and /etc/profile.d/*.sh. Register in all applicable places.
targets=$user_rc
[ "$HOME/.profile" = "$user_rc" ] || targets="$targets $HOME/.profile"
if [ -d /etc/profile.d ] && [ -w /etc/profile.d ]; then
    targets="$targets /etc/profile.d/mini-mvn.sh"
fi

echo "mini-mvn: building engine in $root"
( cd "$root" && sh ./mini-mvn build )

[ -f "$jar" ] || die "artifact was not produced: $jar"

if [ -e "$wrapper" ] && [ "$force" -eq 0 ]; then
    head -n 2 "$wrapper" 2>/dev/null | grep -Fq 'Generated by scripts/install-cli.sh' ||
        die "$wrapper already exists and was not generated by this script (use --force)"
fi

mkdir -p "$bin"
wrapper_tmp=$wrapper.tmp.$$
trap 'rm -f "$wrapper_tmp"' 0 1 2 3 15

cat > "$wrapper_tmp" <<'WRAPPER'
#!/bin/sh
# Generated by scripts/install-cli.sh. Do not edit.
set -eu

here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)
root=$(CDPATH= cd -- "$here/.." && pwd -P)
jar=$root/target/mini-maven/mini-mvn.jar

if [ ! -f "$jar" ]; then
    echo "mini-mvn: $jar is missing; run scripts/install-cli.sh" >&2
    exit 1
fi

jdk=$(sh "$root/scripts/find-jdk17.sh")
java=$jdk/bin/java

# No trailing empty element in the classpath: that would add the caller's cwd.
cp=$jar
jars=$(find "$root/third-party/repository" -type f -name '*.jar' 2>/dev/null | LC_ALL=C sort | paste -sd: -)
[ -z "$jars" ] || cp=$cp:$jars

if [ -n "$(find "$root/mini-maven/src" -type f -name '*.java' -newer "$jar" -print -quit 2>/dev/null)" ]; then
    echo "mini-mvn: engine sources are newer than the jar; run scripts/install-cli.sh" >&2
fi

exec "$java" -Dmini.mvn.home="$root" -cp "$cp" mini.maven.Main "$@"
WRAPPER

chmod 755 "$wrapper_tmp"
mv -f "$wrapper_tmp" "$wrapper"
echo "mini-mvn: installed $wrapper"

if [ "$use_link" -eq 1 ]; then
    if [ -e "$link" ] && [ "$force" -eq 0 ]; then
        head -n 2 "$link" 2>/dev/null | grep -Fq 'Generated by scripts/install-cli.sh' ||
            die "$link already exists and was not generated by this script (use --force)"
    fi
    link_tmp=$link.tmp.$$
    trap 'rm -f "$wrapper_tmp" "$link_tmp"' 0 1 2 3 15
    {
        printf '#!/bin/sh\n'
        printf '# Generated by scripts/install-cli.sh. Do not edit.\n'
        printf 'exec sh %s "$@"\n' "'$(escape_single_quote "$wrapper")'"
    } > "$link_tmp"
    chmod 755 "$link_tmp"
    mv -f "$link_tmp" "$link"
    echo "mini-mvn: installed executable launcher $link -> $wrapper"
fi

# Without a system launcher, a noexec mount needs a shell-function fallback.
fallback=0
if [ "$use_link" -eq 0 ] && [ ! -x "$wrapper" ]; then
    fallback=1
    echo "mini-mvn: filesystem refuses the exec bit; adding an 'sh' fallback" >&2
fi

write_block() {
    target=$1
    tmp=$target.tmp.$$
    filtered=$target.filtered.$$
    trap 'rm -f "$tmp" "$filtered"' 0 1 2 3 15

    if [ -f "$target" ]; then
        cp -p "$target" "$tmp"
        awk -v begin="$marker_begin" -v end="$marker_end" '
            $0 == begin { skip = 1; next }
            $0 == end { skip = 0; next }
            !skip { print }
        ' "$target" > "$filtered"
        cat "$filtered" > "$tmp"
    else
        : > "$tmp"
        chmod 644 "$tmp"
    fi

    {
        printf '\n%s\n' "$marker_begin"
        if [ "$use_link" -eq 1 ]; then
            # Append, so the executable launcher in /usr/local/bin wins.
            printf "export PATH=\"\$PATH:'%s'\"\n" "$(escape_single_quote "$bin")"
        else
            printf "export PATH='%s':\"\$PATH\"\n" "$(escape_single_quote "$bin")"
            if [ "$fallback" -eq 1 ]; then
                printf 'mini-mvn() { sh %s "$@"; }\n' "'$(escape_single_quote "$wrapper")'"
            fi
        fi
        printf '%s\n' "$marker_end"
    } >> "$tmp"

    mv -f "$tmp" "$target"
    echo "mini-mvn: registered $bin on PATH in $target"
}

for target in $targets; do
    write_block "$target"
done

if [ "$use_link" -eq 1 ]; then
    echo "mini-mvn: ready — run 'mini-mvn --help' (new or current shell)"
else
    echo "mini-mvn: open a new terminal, or run '. /etc/profile' / 'source $user_rc'"
fi
